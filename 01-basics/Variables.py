# Variables in Python
first_Name='Prashant'
last_Name='Pandey'
country='India'
city='Bangalore'
age=25
is_Married=False
skills=['HTML','CSS','JavaScript','Python']
person={'first_Name':'Prashant',
        'last_Name':'Pandey',
        'age':25,
        'country':'India',
        'is_Married':False
        }
# Printing the values stored in the variables
print('First Name:',first_Name)
print('Last Name:',last_Name)
print('country:',country)
print('city:',city)
print('age:',age)
print('is_Married:',is_Married)
print('skills:',skills)
print('person:',person)

